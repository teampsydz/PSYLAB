-- Record one pedagogical event and update the user's adaptive mastery estimate.
create or replace function public.record_learning_event(
  p_course_key text,
  p_activity_key text,
  p_competency_key text,
  p_event_type text,
  p_is_correct boolean default null,
  p_answer_code text default null,
  p_metadata jsonb default '{}'::jsonb
) returns jsonb
language plpgsql security definer set search_path=public as $$
declare
  v_uid uuid:=auth.uid();
  v_old numeric;
  v_new numeric;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if p_course_key is null or p_competency_key is null then raise exception 'Invalid event'; end if;
  if pg_column_size(coalesce(p_metadata,'{}'::jsonb)) > 12000 then raise exception 'Event metadata too large'; end if;

  insert into public.learning_events(user_id,course_key,activity_key,competency_key,event_type,is_correct,answer_code,metadata)
  values(v_uid,left(p_course_key,40),left(coalesce(p_activity_key,'unknown'),160),left(p_competency_key,120),left(coalesce(p_event_type,'attempt'),80),p_is_correct,left(p_answer_code,200),coalesce(p_metadata,'{}'::jsonb));

  if p_is_correct is not null then
    select mastery_score into v_old from public.skill_mastery where user_id=v_uid and course_key=p_course_key and competency_key=p_competency_key;
    if v_old is null then v_old:=case when p_is_correct then 60 else 40 end;
    else
      if p_is_correct then v_old:=v_old + (100-v_old)*0.22;
      else v_old:=v_old - v_old*0.30;
      end if;
    end if;
    v_new:=greatest(0,least(100,v_old));
    insert into public.skill_mastery(user_id,course_key,competency_key,attempts,correct_count,error_count,mastery_score,last_seen,updated_at)
    values(v_uid,p_course_key,p_competency_key,1,case when p_is_correct then 1 else 0 end,case when p_is_correct then 0 else 1 end,v_new,now(),now())
    on conflict(user_id,course_key,competency_key) do update set
      attempts=public.skill_mastery.attempts+1,
      correct_count=public.skill_mastery.correct_count+case when p_is_correct then 1 else 0 end,
      error_count=public.skill_mastery.error_count+case when p_is_correct then 0 else 1 end,
      mastery_score=v_new,
      last_seen=now(),updated_at=now();
  end if;
  return jsonb_build_object('ok',true,'mastery',v_new);
end;$$;
revoke all on function public.record_learning_event(text,text,text,text,boolean,text,jsonb) from public;
grant execute on function public.record_learning_event(text,text,text,text,boolean,text,jsonb) to authenticated;

create or replace function public.touch_study_session(
  p_session_id uuid,
  p_course_key text,
  p_active_seconds integer,
  p_event_count integer
) returns jsonb
language plpgsql security definer set search_path=public as $$
declare v_uid uuid:=auth.uid();
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  insert into public.study_sessions(session_id,user_id,course_key,started_at,last_active_at,active_seconds,event_count)
  values(p_session_id,v_uid,left(p_course_key,40),now(),now(),greatest(0,least(coalesce(p_active_seconds,0),86400)),greatest(0,least(coalesce(p_event_count,0),10000)))
  on conflict(session_id) do update set
    last_active_at=now(),
    active_seconds=greatest(public.study_sessions.active_seconds,excluded.active_seconds),
    event_count=greatest(public.study_sessions.event_count,excluded.event_count)
  where public.study_sessions.user_id=v_uid;
  return jsonb_build_object('ok',true);
end;$$;
revoke all on function public.touch_study_session(uuid,text,integer,integer) from public;
grant execute on function public.touch_study_session(uuid,text,integer,integer) to authenticated;

create or replace function public.get_my_learning_dashboard(p_course_key text default 'bipolar')
returns table(dashboard jsonb)
language sql security definer set search_path=public as $$
with me as(select auth.uid() uid),
agg as(
 select
  (select count(distinct date(s.started_at)) from public.study_sessions s,me where s.user_id=me.uid and s.course_key=p_course_key and s.started_at>=now()-interval '7 days' and s.active_seconds>0) active_days_7,
  (select count(distinct date(s.started_at)) from public.study_sessions s,me where s.user_id=me.uid and s.course_key=p_course_key and s.started_at>=now()-interval '30 days' and s.active_seconds>0) active_days_30,
  (select coalesce(sum(s.active_seconds),0) from public.study_sessions s,me where s.user_id=me.uid and s.course_key=p_course_key and s.started_at>=now()-interval '30 days') active_seconds_30,
  (select count(*) from public.learning_events e,me where e.user_id=me.uid and e.course_key=p_course_key and e.created_at>=now()-interval '30 days') event_count_30,
  (select case when count(*) filter(where e.is_correct is not null)=0 then null else round(100.0*count(*) filter(where e.is_correct=true)/count(*) filter(where e.is_correct is not null),1) end from public.learning_events e,me where e.user_id=me.uid and e.course_key=p_course_key and e.created_at>=now()-interval '30 days') accuracy_30
), weak as(
 select coalesce(jsonb_agg(jsonb_build_object('key',x.competency_key,'mastery',round(x.mastery_score),'attempts',x.attempts,'errors',x.error_count) order by x.mastery_score asc,x.error_count desc),'[]'::jsonb) weaknesses
 from (select s.* from public.skill_mastery s,me where s.user_id=me.uid and s.course_key=p_course_key order by s.mastery_score asc,s.error_count desc limit 8) x
), rev as(
 select coalesce(jsonb_agg(jsonb_build_object('at',r.completed_at,'score',r.score) order by r.completed_at),'[]'::jsonb) reviews
 from (select r.* from public.maintenance_reviews r,me where r.user_id=me.uid and r.course_key=p_course_key order by r.completed_at desc limit 24) r
)
select jsonb_build_object('active_days_7',agg.active_days_7,'active_days_30',agg.active_days_30,'active_seconds_30',agg.active_seconds_30,'event_count_30',agg.event_count_30,'accuracy_30',agg.accuracy_30,'weaknesses',weak.weaknesses,'maintenance',jsonb_build_object('reviews',rev.reviews)) from agg,weak,rev;
$$;
revoke all on function public.get_my_learning_dashboard(text) from public;
grant execute on function public.get_my_learning_dashboard(text) to authenticated;

