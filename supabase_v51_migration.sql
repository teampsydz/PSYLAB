-- PsyLab V51 — migration learning analytics + adaptive mastery + maintenance + weekly challenges
-- Run AFTER supabase_schema_v50.sql in Supabase SQL Editor.
-- Stores pedagogical interaction data only. Do not store patient-identifiable information.

create table if not exists public.learning_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  course_key text not null check (course_key ~ '^[a-z0-9_-]{2,40}$'),
  activity_key text not null,
  competency_key text not null,
  event_type text not null,
  is_correct boolean null,
  answer_code text null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists learning_events_user_course_time_idx on public.learning_events(user_id,course_key,created_at desc);
create index if not exists learning_events_course_comp_idx on public.learning_events(course_key,competency_key,created_at desc);

create table if not exists public.skill_mastery (
  user_id uuid not null references auth.users(id) on delete cascade,
  course_key text not null,
  competency_key text not null,
  attempts integer not null default 0,
  correct_count integer not null default 0,
  error_count integer not null default 0,
  mastery_score numeric(5,2) not null default 50 check (mastery_score between 0 and 100),
  last_seen timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key(user_id,course_key,competency_key)
);
create index if not exists skill_mastery_user_course_score_idx on public.skill_mastery(user_id,course_key,mastery_score asc);

create table if not exists public.study_sessions (
  session_id uuid primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  course_key text not null,
  started_at timestamptz not null default now(),
  last_active_at timestamptz not null default now(),
  active_seconds integer not null default 0 check (active_seconds between 0 and 86400),
  event_count integer not null default 0 check (event_count between 0 and 10000)
);
create index if not exists study_sessions_user_course_time_idx on public.study_sessions(user_id,course_key,started_at desc);

create table if not exists public.maintenance_reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  course_key text not null,
  score integer not null check (score between 0 and 100),
  item_count integer not null default 0,
  completed_at timestamptz not null default now()
);
create index if not exists maintenance_reviews_user_course_idx on public.maintenance_reviews(user_id,course_key,completed_at desc);

-- Challenge templates are private. Users receive content through an RPC; answer keys are never granted directly.
create table if not exists public.challenge_templates (
  template_id integer primary key,
  course_key text not null,
  content jsonb not null,
  answer_key jsonb not null,
  max_score integer not null default 100
);

create table if not exists public.challenge_attempts (
  user_id uuid not null references auth.users(id) on delete cascade,
  challenge_key text not null,
  course_key text not null,
  score integer not null check (score between 0 and 100),
  answers jsonb not null default '[]'::jsonb,
  submitted_at timestamptz not null default now(),
  primary key(user_id,challenge_key)
);
create index if not exists challenge_attempts_key_score_idx on public.challenge_attempts(challenge_key,score desc);

-- Optional administrator allow-list. Keep it private.
create table if not exists public.platform_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

