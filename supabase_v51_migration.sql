-- Admin analytics. Add your own auth.users UUID to platform_admins manually after testing.
create or replace function public.get_admin_course_analytics(p_course_key text default 'bipolar',p_days integer default 30)
returns table(analytics jsonb)
language plpgsql security definer set search_path=public as $$
declare v_uid uuid:=auth.uid();v_since timestamptz:=now()-make_interval(days=>greatest(1,least(coalesce(p_days,30),365)));v_result jsonb;
begin
 if v_uid is null or not exists(select 1 from public.platform_admins a where a.user_id=v_uid) then raise exception 'Administrator access required'; end if;
 select jsonb_build_object(
  'active_users', (select count(distinct s.user_id) from public.study_sessions s where s.course_key=p_course_key and s.started_at>=v_since and s.active_seconds>0),
  'sessions', (select count(*) from public.study_sessions s where s.course_key=p_course_key and s.started_at>=v_since and s.active_seconds>0),
  'active_seconds', (select coalesce(sum(s.active_seconds),0) from public.study_sessions s where s.course_key=p_course_key and s.started_at>=v_since),
  'events', (select count(*) from public.learning_events e where e.course_key=p_course_key and e.created_at>=v_since),
  'accuracy', (select case when count(*) filter(where e.is_correct is not null)=0 then null else round(100.0*count(*) filter(where e.is_correct=true)/count(*) filter(where e.is_correct is not null),1) end from public.learning_events e where e.course_key=p_course_key and e.created_at>=v_since),
  'top_errors', (select coalesce(jsonb_agg(jsonb_build_object('competency_key',x.competency_key,'errors',x.errors,'attempts',x.attempts) order by x.errors desc),'[]'::jsonb) from (select e.competency_key,count(*) filter(where e.is_correct=false) errors,count(*) filter(where e.is_correct is not null) attempts from public.learning_events e where e.course_key=p_course_key and e.created_at>=v_since group by e.competency_key having count(*) filter(where e.is_correct=false)>0 order by errors desc limit 12) x)
 ) into v_result;
 analytics:=v_result;return next;
end;$$;
revoke all on function public.get_admin_course_analytics(text,integer) from public;
grant execute on function public.get_admin_course_analytics(text,integer) to authenticated;

