create or replace function public.get_current_challenge(p_course_key text default 'bipolar')
returns table(challenge_key text,starts_at timestamptz,ends_at timestamptz,content jsonb)
language plpgsql security definer set search_path=public as $$
declare v_count int;v_id int;v_start timestamptz;v_content jsonb;
begin
 if auth.uid() is null then raise exception 'Authentication required'; end if;
 select count(*) into v_count from public.challenge_templates where course_key=p_course_key;
 if v_count=0 then return; end if;
 v_start:=date_trunc('week',now());
 v_id:=(extract(week from v_start)::int % v_count)+1;
 select c.content into v_content from public.challenge_templates c where c.course_key=p_course_key and c.template_id=v_id;
 challenge_key:=p_course_key||'-'||to_char(v_start,'IYYY-IW');starts_at:=v_start;ends_at:=v_start+interval '7 days';content:=v_content;return next;
end;$$;
revoke all on function public.get_current_challenge(text) from public;
grant execute on function public.get_current_challenge(text) to authenticated;

create or replace function public.submit_weekly_challenge(p_challenge_key text,p_answers jsonb)
returns table(score integer,accepted boolean)
language plpgsql security definer set search_path=public as $$
declare
 v_uid uuid:=auth.uid();v_start timestamptz:=date_trunc('week',now());v_expected_key text;v_count int;v_id int;v_key jsonb;v_i int;v_choice int;v_correct int;v_conf int;v_score int:=0;v_existing int;
begin
 if v_uid is null then raise exception 'Authentication required'; end if;
 select count(*) into v_count from public.challenge_templates where course_key='bipolar';
 if v_count=0 then raise exception 'No challenge template'; end if;
 v_id:=(extract(week from v_start)::int % v_count)+1;v_expected_key:='bipolar-'||to_char(v_start,'IYYY-IW');
 if p_challenge_key<>v_expected_key then raise exception 'Challenge is not current'; end if;
 select answer_key into v_key from public.challenge_templates where course_key='bipolar' and template_id=v_id;
 if jsonb_typeof(p_answers)<>'array' or jsonb_array_length(p_answers)<>jsonb_array_length(v_key->'correct') then raise exception 'Incomplete challenge'; end if;
 select ca.score into v_existing from public.challenge_attempts ca where ca.user_id=v_uid and ca.challenge_key=p_challenge_key;
 if v_existing is not null then score:=v_existing;accepted:=false;return next;return;end if;
 for v_i in 0..jsonb_array_length(p_answers)-1 loop
   v_choice:=coalesce((p_answers->v_i->>'choice')::int,-1);v_conf:=greatest(0,least(coalesce((p_answers->v_i->>'confidence')::int,70),100));v_correct:=(v_key->'correct'->>v_i)::int;
   if v_choice=v_correct then
     v_score:=v_score+16;
     v_score:=v_score+case when v_conf>=85 then 4 when v_conf>=65 then 3 else 2 end;
   else
     v_score:=v_score+case when v_conf<=55 then 4 when v_conf<=75 then 2 else 0 end;
   end if;
 end loop;
 v_score:=greatest(0,least(v_score,100));
 insert into public.challenge_attempts(user_id,challenge_key,course_key,score,answers) values(v_uid,p_challenge_key,'bipolar',v_score,p_answers);
 score:=v_score;accepted:=true;return next;
end;$$;
revoke all on function public.submit_weekly_challenge(text,jsonb) from public;
grant execute on function public.submit_weekly_challenge(text,jsonb) to authenticated;

create or replace function public.get_challenge_leaderboard(p_challenge_key text,p_limit integer default 20)
returns table(rank bigint,user_id uuid,display_name text,cohort_code text,score integer,submitted_at timestamptz)
language sql security definer set search_path=public as $$
with base as(
 select ca.user_id,p.display_name,p.cohort_code,ca.score,ca.submitted_at
 from public.challenge_attempts ca join public.profiles p on p.id=ca.user_id
 where ca.challenge_key=p_challenge_key
), ranked as(
 select rank() over(order by score desc) rank,* from base
)
select r.rank,r.user_id,r.display_name,r.cohort_code,r.score,r.submitted_at from ranked r order by r.rank,r.display_name limit greatest(1,least(coalesce(p_limit,20),100));
